# Summarizes Native AOT publish warnings and smoke-test runs into aot-warnings-baseline.txt.
# Inputs in -ScratchDir: <tfm>-warn.log (from: dotnet publish tests/AotSmokeTests -c Release -f <tfm> -r win-x64 "-flp:warningsonly;logfile=<dir>\<tfm>-warn.log")
#                       run-<tfm>-w<0|1>.txt (exe output with AOT_SMOKE_WORKAROUNDS=0/1).
# On Windows with .NET 8 ILCompiler, put the VS Installer folder (vswhere.exe) on PATH before publishing.
param([string]$ScratchDir, [string]$RepoRoot, [string]$OutFile)

$repo = $RepoRoot.TrimEnd('\') + '\'
$rx = '^\s*\d+>(?<loc>.+?)\((?<line>\d+)\): (?<kind>Trim|AOT) analysis warning (?<code>IL\d+): (?<member>.+?): (?<msg>.*?) \[[^\]]+\]\s*$'
$rxNoLoc = '^\s*\d+>(?<loc>[^:]+) : (?<kind>Trim|AOT) analysis warning (?<code>IL\d+): (?<msg>.*?) \[[^\]]+\]\s*$'

function Parse([string]$path) {
    foreach ($l in Get-Content $path) {
        if ($l -match $rx) {
            $m = $Matches.Clone()
            $loc = $m.loc
            $file = if ($loc.StartsWith($repo, 'OrdinalIgnoreCase')) { $loc.Substring($repo.Length) } else { $loc }
            $assembly =
                if ($file -match '^src\\(MongoDB\.[^\\]+)\\') { $Matches[1] }
                elseif ($file -match '^/_/src/libraries/([^/]+)/') { "$($Matches[1]) (framework)" }
                elseif ($file -match '^tests\\') { 'AotSmokeTests' }
                else { 'other: ' + ($file -split '[\\/]')[0] }
            $area = if ($file -match '^src\\') { (Split-Path $file -Parent) -replace '^src\\', '' } elseif ($file -match '^/_/src/libraries/([^/]+)/') { $Matches[1] } else { $file }
            [pscustomobject]@{ Code = $m.code; Kind = $m.kind; File = $file; Line = [int]$m.line; Assembly = $assembly; Area = $area; Member = $m.member; Raw = "$file($($m.line)): $($m.kind) analysis warning $($m.code): $($m.member): $($m.msg)" }
        }
        elseif ($l -match $rxNoLoc) {
            [pscustomobject]@{ Code = $Matches.code; Kind = $Matches.kind; File = $Matches.loc; Line = 0; Assembly = 'unattributed (' + $Matches.loc + ')'; Area = $Matches.loc; Member = ''; Raw = "$($Matches.loc): $($Matches.kind) analysis warning $($Matches.code): $($Matches.msg)" }
        }
        elseif ($l.Trim()) {
            [pscustomobject]@{ Code = 'UNPARSED'; Kind = ''; File = ''; Line = 0; Assembly = 'unparsed'; Area = ''; Member = ''; Raw = $l.Trim() }
        }
    }
}

function Table($items, [string]$prop, [int]$top = 0) {
    $g = $items | Group-Object $prop | Sort-Object @{ e = 'Count'; Descending = $true }, Name
    if ($top -gt 0) { $g = $g | Select-Object -First $top }
    $g | ForEach-Object { '  {0,5}  {1}' -f $_.Count, $_.Name }
}

$out = [System.Collections.Generic.List[string]]::new()
$out.Add('Native AOT warnings baseline - tests/AotSmokeTests')
$out.Add('===================================================')
$out.Add('')
$out.Add('Generated by: dotnet publish tests/AotSmokeTests -c Release -f <tfm> -r win-x64  (PublishAot=true, TrimmerSingleWarn=false)')
$out.Add("Branch base: $(git -C $RepoRoot rev-parse --short HEAD) ($(git -C $RepoRoot log -1 --format=%s HEAD))")
$out.Add("SDKs: $((dotnet --list-sdks) -replace ' \[.*\]', '' -join ', '); ILCompiler 8.0.31 (net8.0), runtime pack 10.0.12 (net10.0)")
$out.Add('Note: ILC reports warnings only for code reachable from the smoke test, so this is the reachable surface,')
$out.Add('      not every reflection use in the driver. Each IL2xxx/IL3xxx call site is listed separately.')
$out.Add('')

$out.Add('################ Run results against local mongod (mongodb://localhost:27017) ################')
$out.Add('AOT_SMOKE_WORKAROUNDS=0 is the raw baseline; =1 pre-registers serializers app-side so later steps are reached.')
$out.Add('')
foreach ($tfm in 'net8.0', 'net10.0') {
    foreach ($w in '0', '1') {
        $out.Add("[$tfm, AOT_SMOKE_WORKAROUNDS=$w]")
        $lines = Get-Content (Join-Path $ScratchDir "run-$tfm-w$w.txt")
        foreach ($l in $lines) {
            if ($l -match '^(Runtime|PASS|FAIL|ALL|\d+ STEP)') {
                $text = if ($l -match '^FAIL connect') { $l -replace 'Client view of cluster state.*$', '...' } else { $l }
                $out.Add('  ' + $text)
            }
            elseif ($l -match '^\s+---> (.*)$') {
                $out.Add('      inner: ' + $Matches[1])
            }
        }
        $out.Add('')
    }
}

$all = @{}
foreach ($tfm in 'net8.0', 'net10.0') {
    $w = @(Parse (Join-Path $ScratchDir "$tfm-warn.log"))
    $all[$tfm] = $w
    $out.Add("################ $tfm : $($w.Count) warnings ################")
    $out.Add('')
    $out.Add('By warning code:')
    Table $w 'Code' | ForEach-Object { $out.Add($_) }
    $out.Add('')
    $out.Add('By assembly:')
    Table $w 'Assembly' | ForEach-Object { $out.Add($_) }
    $out.Add('')
    $out.Add('By assembly x code:')
    $w | Group-Object Assembly, Code | Sort-Object Name | ForEach-Object { $out.Add(('  {0,5}  {1}' -f $_.Count, $_.Name)) }
    $out.Add('')
    $out.Add('By source folder (namespace area):')
    Table $w 'Area' | ForEach-Object { $out.Add($_) }
    $out.Add('')
    $out.Add('Top 10 source files:')
    Table $w 'File' 10 | ForEach-Object { $out.Add($_) }
    $out.Add('')
    $out.Add('Distinct members with warnings:')
    $out.Add(('  {0}' -f ($w | Select-Object -ExpandProperty Member -Unique).Count))
    $out.Add('')
}

foreach ($tfm in 'net8.0', 'net10.0') {
    $out.Add("################ Raw warnings: $tfm ################")
    $all[$tfm] | ForEach-Object { $out.Add($_.Raw) }
    $out.Add('')
}

[System.IO.File]::WriteAllLines($OutFile, $out, [System.Text.UTF8Encoding]::new($false))
